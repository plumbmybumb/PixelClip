/// The clip's own system screens ("WiFi: PixelClip-…", "Done", "Battery low", "bye"), drawn exactly like
/// `firmware/components/ui/ui.c` does: the classic 5×7 bitmap font scaled 3–4×, centred, on black.
/// Used for the onboarding and connection-help illustrations, so what they show is what the clip shows.
public enum SystemScreen {
    public static let white = (r: 255, g: 255, b: 255)
    public static let done = (r: 120, g: 255, b: 160)
    public static let warning = (r: 255, g: 80, b: 60)
    public static let secondary = (r: 160, g: 160, b: 160)
    /// The brand accent, as the firmware's `UI_ACCENT` (soft violet #C6A2FF, `BrandPalette.primary`).
    public static let accent = (r: Int(BrandPalette.primary >> 16), g: Int(BrandPalette.primary >> 8 & 0xFF), b: Int(BrandPalette.primary & 0xFF))
    /// Battery-low orange (the app's `.orange` for "charge soon").
    static let low = (r: 255, g: 159, b: 10)

    /// `ui_screen_message(line1, line2, color)`.
    public static func message(_ line1: String, _ line2: String? = nil,
                               color: (r: Int, g: Int, b: Int) = white) -> CGImage {
        var px = [UInt8](repeating: 0, count: ClipCanvas.width * ClipCanvas.height * 4)
        for i in stride(from: 3, to: px.count, by: 4) { px[i] = 255 }
        let w = ClipCanvas.width, h = ClipCanvas.height
        let scale1 = textWidth(4, line1) <= w - 16 ? 4 : 3
        if let line2 {
            text(&px, centeredY: 70, scale: scale1, color: color, line1)
            let scale2 = textWidth(3, line2) <= w - 16 ? 3 : 2
            text(&px, centeredY: 70 + 7 * scale1 + 24, scale: scale2, color: secondary, line2)
        } else {
            text(&px, centeredY: (h - 7 * scale1) / 2, scale: scale1, color: color, line1)
        }
        return image(px)
    }

    /// A blank (switched-off) panel.
    public static func off() -> CGImage {
        var px = [UInt8](repeating: 0, count: ClipCanvas.width * ClipCanvas.height * 4)
        for i in stride(from: 3, to: px.count, by: 4) { px[i] = 255 }
        return image(px)
    }

    /// A blocky battery (the system screens' pixel style) with `bars` of 4 lit and a caption, for
    /// the onboarding's charging page. One bar is battery-low orange, two or three the brand violet,
    /// four (full) green.
    public static func charging(bars: Int, caption: String = "USB-C") -> CGImage {
        var px = [UInt8](repeating: 0, count: ClipCanvas.width * ClipCanvas.height * 4)
        for i in stride(from: 3, to: px.count, by: 4) { px[i] = 255 }
        let outline = (r: 220, g: 220, b: 220)
        let lit = bars >= 4 ? done : (bars <= 1 ? low : accent)
        // Body 168×84 with an 8 px wall, plus a 12×36 nub; centred above the caption.
        let bw = 168, bh = 84, wall = 8, nubW = 12, nubH = 36
        let x0 = (ClipCanvas.width - bw - nubW) / 2, y0 = 52
        fill(&px, x: x0, y: y0, w: bw, h: wall, color: outline)
        fill(&px, x: x0, y: y0 + bh - wall, w: bw, h: wall, color: outline)
        fill(&px, x: x0, y: y0, w: wall, h: bh, color: outline)
        fill(&px, x: x0 + bw - wall, y: y0, w: wall, h: bh, color: outline)
        fill(&px, x: x0 + bw, y: y0 + (bh - nubH) / 2, w: nubW, h: nubH, color: outline)
        let inner = bw - 2 * wall - 8, barGap = 8
        let barW = (inner - 3 * barGap) / 4
        for b in 0..<min(max(bars, 0), 4) {
            fill(&px, x: x0 + wall + 4 + b * (barW + barGap), y: y0 + wall + 4, w: barW, h: bh - 2 * wall - 8, color: lit)
        }
        text(&px, centeredY: y0 + bh + 30, scale: 3, color: secondary, caption)
        return image(px)
    }

    static func textWidth(_ scale: Int, _ s: String) -> Int {
        let n = s.unicodeScalars.count
        return n == 0 ? 0 : (n * 6 - 1) * scale
    }

    static func text(_ px: inout [UInt8], centeredY y: Int, scale: Int, color: (r: Int, g: Int, b: Int), _ s: String) {
        var x = (ClipCanvas.width - textWidth(scale, s)) / 2
        for u in s.unicodeScalars {
            let c = (0x20...0x7E).contains(u.value) ? Int(u.value) : 0x3F
            let g = font[c - 0x20]
            for col in 0..<5 {
                for row in 0..<7 where g[col] & (1 << row) != 0 {
                    fill(&px, x: x + col * scale, y: y + row * scale, w: scale, h: scale, color: color)
                }
            }
            x += 6 * scale
        }
    }

    static func fill(_ px: inout [UInt8], x: Int, y: Int, w: Int, h: Int, color: (r: Int, g: Int, b: Int)) {
        let W = ClipCanvas.width, H = ClipCanvas.height
        for yy in max(0, y)..<min(H, y + h) {
            for xx in max(0, x)..<min(W, x + w) {
                let i = (yy * W + xx) * 4
                px[i] = UInt8(color.r); px[i + 1] = UInt8(color.g); px[i + 2] = UInt8(color.b); px[i + 3] = 255
            }
        }
    }

    static func image(_ px: [UInt8]) -> CGImage {
        let W = ClipCanvas.width, H = ClipCanvas.height
        let provider = CGDataProvider(data: Data(px) as CFData)!
        return CGImage(width: W, height: H, bitsPerComponent: 8, bitsPerPixel: 32, bytesPerRow: W * 4,
                       space: ClipRenderer.srgb, bitmapInfo: CGBitmapInfo(rawValue: CGImageAlphaInfo.premultipliedLast.rawValue),
                       provider: provider, decode: nil, shouldInterpolate: false, intent: .defaultIntent)!
    }

